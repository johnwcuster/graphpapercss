function defineGrid(id, weights) {
  const match = id.match(/^grid_(0\d[a-d]?)(?:--(\d{2}))?$/);
  if (!match) throw new Error(`Invalid grid recipe ID: ${id}`);
  return [id, { id, columns: weights.length, family: match[1], weights,
    variant: match[2] ?? null, legacy: true }];
}

